    def setKriggingModel(self):

        if self.krigging_model == "exp":

            def target_model(h, nugget, sill, emp_range):

                partial_sill = sill - nugget
                gamma = nugget + partial_sill * (1 - np.exp(-h / emp_range))
                gamma = np.where(h == 0, 0, gamma)

                return gamma

            self.model_function = target_model
        
        elif self.krigging_model == "gau":

            def target_model(h, nugget, sill, emp_range):

                partial_sill = sill - nugget
                gamma = nugget + partial_sill * (1 - np.exp(-(h**2) / (emp_range**2)))
                gamma = np.where(h == 0, 0, gamma)

                return gamma
            
            self.model_function = target_model

        elif self.krigging_model == "sph":

            def target_model(h, nugget, sill, emp_range):

                partial_sill = sill - nugget
                gamma = np.where(
                    h <= emp_range,
                    nugget + partial_sill * (1.5 * (h / emp_range) - 0.5 * (h / emp_range)**3),
                    sill
                )

                gamma = np.where(h == 0, 0, gamma)

                return gamma
            
            self.model_function = target_model

