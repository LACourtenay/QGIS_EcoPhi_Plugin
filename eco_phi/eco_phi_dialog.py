    def createRaster(self):

        rows, cols = self.phi_raster_t.shape
        minx, miny, maxx, maxy = self.grid_extent
        pixel_width = self.spacing
        pixel_height = self.spacing

        filepath, _ = QFileDialog.getSaveFileName(
            self,
            "Save raster",
            f"{self.outputName}.tif",
            "GeoTiff (*.tif)"
        )

        if not filepath:
            return

        driver = gdal.GetDriverByName("GTiff")

        dataset = driver.Create(
            filepath,
            cols,
            rows,
            1,
            gdal.GDT_Float32,
            options = ["COMPRESS=LZW"]
        )

        if dataset is None:

            QMessageBox.critical(
                self,
                "Raster creation failed",
                "Could not create the output raster."
            )

            return

        dataset.SetGeoTransform(
            (
                minx,
                pixel_width,
                0,
                maxy,
                0,
                -pixel_height
            )
        )

        spatial_reference = osr.SpatialReference()
        spatial_reference.ImportFromEPSG(4326)
        dataset.SetProjection(
            spatial_reference.ExportToWkt()
        )

        band = dataset.GetRasterBand(1)
        band.WriteArray(self.phi_raster_t)

        band.SetNoDataValue(self.nodata_value)

        band.FlushCache()
        dataset.FlushCache()
        dataset = None

        raster_layer = QgsRasterLayer(
            filepath,
            self.outputName
        )

        if not raster_layer.isValid():

            QMessageBox.critical(
                self,
                "Raster loading failed",
                "The raster was created but could not be loaded into QGIS."
            )

            return
        
        QgsProject.instance().addMapLayer(raster_layer)

        QMessageBox.information(
            self,
            "EcoPhi — Calculation Complete",
            f"The EcoPhi calculation was completed successfully.\n\n"
            f"Raster: {self.outputName}\n\n"
            f"Reminder: phi is a circular variable. Therefore, if you wish to "
            f"create visually accurate maps, a cyclic colour palette is required."
        )

    def perform_predictions(self):
        
        orbital_today = self.la2004[self.la2004["t"] == 0].iloc[0]

        long_inside = self.long_flat[self.inside_mask]
        lat_inside = self.lat_flat[self.inside_mask]
        lat_inside_rad = np.radians(lat_inside)

