    def plot_variogram(
        self, lag_centers,
        gamma_hat, n_pairs,
        model_func = None,
        popt = None,
        title="Empirical Semivariogram"
    ):
        
        self.figure.clear()
        ax = self.figure.add_subplot(111)

        valid = (
            (n_pairs > 0) &
            np.isfinite(gamma_hat)
        )

        ax.scatter(
            lag_centers[valid],
            gamma_hat[valid],
            s=100,
            edgecolor="k",
            alpha=0.7
        )

        if model_func is not None and popt is not None:

            h_smooth = np.linspace(
                0,
                lag_centers[valid].max(),
                200
            )

            ax.plot(
                h_smooth,
                model_func(h_smooth, *popt),
                linewidth=2,
                c = "red",
                label="Fitted model"
            )

            ax.legend()

        ax.set_ylabel(r"$\hat{\gamma}(h)$")
        ax.set_xlabel(r"$h$")
        ax.set_title(title)

        ax.set_ylim(
            0,
            np.nanmax(gamma_hat) + np.nanstd(gamma_hat)
        )

        ax.grid(alpha=0.3)

        self.figure.tight_layout()

        self.canvas.draw()
    
