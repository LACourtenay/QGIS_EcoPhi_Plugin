    def createKrigGrid(self):

        layer_id = self.comboWindow.currentData()

        if not layer_id:
            return

        layer = QgsProject.instance().mapLayer(layer_id)

        if layer is None:
            return

        self.window = gpd.GeoDataFrame.from_features(
            layer.getFeatures(),
            crs=layer.crs().authid()
        )

        self.window = self.window.to_crs("EPSG:4326")

        minx, miny, maxx, maxy = self.window.total_bounds
        self.grid_extent = (minx, miny, maxx, maxy)

        krigging_resolution = self.spacing

        grid_long = np.arange(minx, maxx, krigging_resolution)
        grid_lat = np.arange(miny, maxy, krigging_resolution)
        self.grid_long_mesh, self.grid_lat_mesh = np.meshgrid(grid_long, grid_lat)

        self.long_flat = self.grid_long_mesh.ravel()
        self.lat_flat = self.grid_lat_mesh.ravel()

        points = gpd.GeoSeries([Point(x, y) for x, y in zip(self.long_flat, self.lat_flat)], crs="EPSG:4326")
        window_union = self.window.union_all()
        self.inside_mask = points.within(window_union).values

